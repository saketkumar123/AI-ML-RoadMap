# create and print String
myName = "Saket Kumar"
print(myName)

# Use f-string
print(f"My name is: {myName}")

# Use string methods (upper, lower, title)
print(myName.upper())
print(myName.lower())
print(myName.title())

# Create lists
cart = ["Apple", "Banana", "Mango"]
print(cart)

# Add Items to a list
cart.append("Grapes")
print(cart)

# Remove Items to a list
cart.remove("Apple")
print(cart)

# Loop through a list
for crt in cart:
    print(crt)
